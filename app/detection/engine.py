from sqlalchemy.orm import Session

from app.database.models import Event
from app.detection.brute_force import BruteForceDetector
from app.detection.suspicious_login import SuspiciousLoginDetector
from app.detection.multiple_users import MultipleUsersDetector
from app.detection.port_scan import PortScanDetector
from app.detection.sudo_authentication import SudoAuthenticationDetector
from app.detection.suspicious_sudo import SuspiciousSudoDetector
from app.incident.manager import IncidentManager
from app.services.detection_rule_service import is_rule_enabled
from app.detection.repeated_privilege_escalation import (
    RepeatedPrivilegeEscalationDetector,
)
from app.detection.suspicious_pkexec import SuspiciousPkexecDetector
from app.detection.auth_privilege_correlation import (
    AuthPrivilegeCorrelationDetector,
)


class DetectionEngine:
    """
    Central engine responsible for running
    security detection rules against events.
    """

    @staticmethod
    def _handle_alert(
        db: Session,
        alert,
        event: Event,
        alerts: list,
    ) -> None:
        """
        Record a generated alert, create its incident,
        and print a summary.

        This is only ever called when an alert exists,
        so `incident` is always assigned before use.
        """

        alerts.append(alert)

        incident = IncidentManager.create_for_alert(
            db=db,
            alert=alert,
            reference_time=event.timestamp,
        )

        print("\n🚨 INCIDENT CREATED")
        print(f"  Incident ID: {incident.id}")
        print(f"  Alert ID: {alert.id}")
        print(f"  Severity: {incident.severity}")
        print(f"  Status: {incident.status}")

    @classmethod
    def process_event(
        cls,
        db: Session,
        event: Event,
    ) -> list:
        """
        Process a newly stored event through
        all applicable detection rules.

        Returns:
            A list of alerts generated by the rules.
        """

        alerts = []

        # ==================================================
        # RULE 1: SSH BRUTE FORCE
        # ==================================================

        if (
            event.event_type == "authentication"
            and event.status == "failure"
            and event.src_ip
            and is_rule_enabled("ssh_brute_force")
        ):
            alert = BruteForceDetector.detect(
                db=db,
                src_ip=event.src_ip,
                reference_time=event.timestamp,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 2: SUCCESSFUL LOGIN AFTER MULTIPLE FAILURES
        # ==================================================

        if (
            event.event_type == "authentication"
            and event.status == "success"
            and event.src_ip
            and is_rule_enabled("successful_login_after_failures")
        ):
            alert = SuspiciousLoginDetector.detect(
                db=db,
                event=event,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 3: MULTIPLE USERS FROM SAME SOURCE IP
        # ==================================================

        if (
            event.event_type == "authentication"
            and event.status == "failure"
            and event.src_ip
            and is_rule_enabled("multiple_users_same_ip")
        ):
            alert = MultipleUsersDetector.detect(
                db=db,
                src_ip=event.src_ip,
                reference_time=event.timestamp,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 4: PORT SCAN
        # ==================================================

        if (
            event.event_type == "network_connection"
            and event.src_ip
            and event.dst_port is not None
            and is_rule_enabled("port_scan")
        ):
            alert = PortScanDetector.detect(
                db=db,
                src_ip=event.src_ip,
                reference_time=event.timestamp,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 5: SUDO AUTHENTICATION FAILURE
        # ==================================================

        if (
            event.event_type == "authentication"
            and event.action == "sudo_authentication"
            and event.status == "failure"
            and is_rule_enabled("sudo_authentication_failure")
        ):
            alert = SudoAuthenticationDetector.detect(
                db=db,
                event=event,
                threshold=3,
                window_minutes=5,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)
        # ==================================================
        # RULE 6: SUSPICIOUS SUDO COMMAND
        # ==================================================

        if (
            event.event_type == "privilege_escalation"
            and event.action == "sudo_command"
            and event.status == "success"
            and is_rule_enabled("suspicious_sudo_command")
        ):
            alert = SuspiciousSudoDetector.detect(
                db=db,
                event=event,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 7: REPEATED PRIVILEGE ESCALATION
        # ==================================================

        if (
            event.event_type == "privilege_escalation"
            and event.status == "success"
            and event.username
            and is_rule_enabled("repeated_privilege_escalation")
        ):
            alert = RepeatedPrivilegeEscalationDetector.detect(
                db=db,
                event=event,
                threshold=3,
                window_minutes=5,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 8: SUSPICIOUS PKEXEC ACTIVITY
        # ==================================================

        if (
            event.event_type == "privilege_escalation"
            and event.action == "pkexec_session_open"
            and event.status == "success"
            and event.username
            and is_rule_enabled("suspicious_pkexec_activity")
        ):
            alert = SuspiciousPkexecDetector.detect(
                db=db,
                event=event,
            )

            if alert:
                cls._handle_alert(db, alert, event, alerts)

        # ==================================================
        # RULE 9: AUTHENTICATION → PRIVILEGE ESCALATION
        # ==================================================

        if (
            event.event_type == "privilege_escalation"
            and event.status == "success"
            and event.username
            and is_rule_enabled("authentication_privilege_correlation")
        ):
            alert = AuthPrivilegeCorrelationDetector.detect(
                db=db,
                event=event,
                failure_threshold=3,
                window_minutes=5,
            )

            if alert:
                cls._handle_alert(
                    db,
                    alert,
                    event,
                    alerts,
                )
        return alerts
